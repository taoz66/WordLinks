import Foundation
import Markdown

enum ArticleBodyFormat {
    case automatic
    case plainText
    case markdown
}

enum ArticleDraftError: LocalizedError {
    case unsupportedFile
    case unsupportedEncoding
    case emptyFile

    var errorDescription: String? {
        switch self {
        case .unsupportedFile:
            return L("请选择 Markdown（.md、.markdown）或纯文本（.txt）文件。", "Choose a Markdown (.md, .markdown) or plain text (.txt) file.")
        case .unsupportedEncoding:
            return L("无法读取文本编码。请在文本编辑器中将文件另存为 UTF-8，再导入。", "The text encoding could not be read. Save the file as UTF-8 in a text editor and import it again.")
        case .emptyFile:
            return L("文件没有可阅读的文字。", "The file contains no readable text.")
        }
    }
}

/// An editable import form. Its Markdown is generated by the app, while an
/// untouched Markdown file keeps its exact original contents for linked edits.
struct ArticleDraft: Identifiable {
    var id = UUID()
    var title = ""
    var body = ""
    var author = ""
    var date = ""
    var source = ""
    var sourceURL = ""
    var contentFormat: ArticleBodyFormat = .automatic
    var sourceFileURL: URL?
    var keepsSourceLinked = false
    var notices: [String] = []
    var fileName = "article.md"

    private var originalMarkdown: String?
    private var originalFields: Fields?
    private var linkedMarkdown: String?

    init() {}

    var validationMessage: String? {
        if title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return L("请填写文章标题。", "Enter an article title.")
        }
        if body.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return L("请粘贴或填写文章正文。", "Paste or enter the article text.")
        }
        if !sourceURL.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && normalizedSourceURL == nil {
            return L("原文链接需要是有效的 http 或 https 网址。", "The original link must be a valid http or https address.")
        }
        return nil
    }

    var canSave: Bool { validationMessage == nil }

    /// New forms detect formatting without rewriting the user's fields. File
    /// imports retain the format supplied by their extension.
    var resolvedContentFormat: ArticleBodyFormat {
        contentFormat == .automatic ? Self.detectBodyFormat(body) : contentFormat
    }

    var markdown: String {
        if keepsSourceLinked, sourceFileURL != nil, let linkedMarkdown { return linkedMarkdown }
        if fields == originalFields, let originalMarkdown { return originalMarkdown }
        var sections = ["# " + Self.escapeInline(Self.singleLine(title))]
        var metadata: [String] = []
        let cleanAuthor = Self.singleLine(author)
        let cleanDate = Self.singleLine(date)
        let cleanSource = Self.singleLine(source)
        if !cleanAuthor.isEmpty { metadata.append("Author: " + cleanAuthor) }
        if !cleanDate.isEmpty { metadata.append("Date: " + cleanDate) }
        if let url = normalizedSourceURL {
            let label = cleanSource.isEmpty ? (URL(string: url)?.host ?? url) : cleanSource
            let safeLabel = label.replacingOccurrences(of: "\\", with: "\\\\")
                .replacingOccurrences(of: "[", with: "\\[")
                .replacingOccurrences(of: "]", with: "\\]")
            let target = url.replacingOccurrences(of: "(", with: "%28").replacingOccurrences(of: ")", with: "%29")
            metadata.append("Source: [\(safeLabel)](\(target))")
        } else if !cleanSource.isEmpty {
            metadata.append("Source: " + cleanSource)
        }
        if !metadata.isEmpty { sections.append(metadata.joined(separator: "\n")) }
        let normalizedBody = Self.normalized(body).trimmingCharacters(in: .newlines)
        sections.append(resolvedContentFormat == .plainText
                        ? Self.plainTextMarkdown(normalizedBody) : Self.protectBodyMetadata(normalizedBody))
        return sections.joined(separator: "\n\n") + "\n"
    }

    static func read(from url: URL) throws -> ArticleDraft {
        guard ["md", "markdown", "txt"].contains(url.pathExtension.lowercased()) else {
            throw ArticleDraftError.unsupportedFile
        }
        let data = try Data(contentsOf: url)
        let text: String
        var encodingNotice: String?
        if data.starts(with: [0xFF, 0xFE]) {
            guard let decoded = String(data: data.dropFirst(2), encoding: .utf16LittleEndian) else {
                throw ArticleDraftError.unsupportedEncoding
            }
            text = decoded
            encodingNotice = L("已识别 UTF-16 文本；保存的副本将使用 UTF-8，原文件不会改写。", "UTF-16 text was detected. The saved copy will use UTF-8; the original file will not be changed.")
        } else if data.starts(with: [0xFE, 0xFF]) {
            guard let decoded = String(data: data.dropFirst(2), encoding: .utf16BigEndian) else {
                throw ArticleDraftError.unsupportedEncoding
            }
            text = decoded
            encodingNotice = L("已识别 UTF-16 文本；保存的副本将使用 UTF-8，原文件不会改写。", "UTF-16 text was detected. The saved copy will use UTF-8; the original file will not be changed.")
        } else {
            guard String(data: data, encoding: .utf8) != nil else { throw ArticleDraftError.unsupportedEncoding }
            // Foundation's encoding initializer consumes a UTF-8 BOM. The
            // validated decoder retains it so an untouched file round-trips.
            text = String(decoding: data, as: UTF8.self)
        }
        guard !text.contains("\0") else { throw ArticleDraftError.unsupportedEncoding }
        guard !normalized(text).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw ArticleDraftError.emptyFile
        }
        let fallback = url.deletingPathExtension().lastPathComponent
        let format: ArticleBodyFormat = url.pathExtension.lowercased() == "txt" ? .plainText : .markdown
        var draft = prepare(text, format: format, fallbackTitle: fallback)
        draft.fileName = format == .plainText ? url.deletingPathExtension().lastPathComponent + ".md" : url.lastPathComponent
        draft.sourceFileURL = url.standardizedFileURL
        if let encodingNotice { draft.notices.insert(encodingNotice, at: 0) }
        draft.linkedMarkdown = draft.markdown
        return draft
    }

    static func pasted(_ text: String) -> ArticleDraft {
        let normalizedText = normalized(text)
        let first = normalizedText.components(separatedBy: "\n").first { !$0.trimmingCharacters(in: .whitespaces).isEmpty } ?? ""
        let isMarkdown = heading(first) != nil || first.trimmingCharacters(in: .whitespaces) == "---"
        if isMarkdown {
            return prepare(text, format: .markdown, fallbackTitle: L("新文章", "New Article"))
        }
        var draft = prepare(text, format: .plainText, fallbackTitle: L("新文章", "New Article"), reportFallback: false)
        let suggestion = first.trimmingCharacters(in: .whitespacesAndNewlines)
        if !suggestion.isEmpty, suggestion.count <= 100 { draft.title = suggestion }
        // The suggested first line remains in the body so pasting cannot erase prose.
        return draft
    }

    private struct Fields: Equatable {
        var title: String
        var body: String
        var author: String
        var date: String
        var source: String
        var sourceURL: String
        var format: ArticleBodyFormat
    }

    private var fields: Fields {
        Fields(title: title, body: body, author: author, date: date,
               source: source, sourceURL: sourceURL, format: contentFormat)
    }

    private var normalizedSourceURL: String? {
        var value = sourceURL.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !value.isEmpty else { return nil }
        if !value.contains(":"), value.contains("."), !value.contains(where: \.isWhitespace) {
            value = "https://" + value
        }
        guard let url = URL(string: value), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
              let host = url.host, !host.isEmpty else { return nil }
        return url.absoluteString
    }

    private static func prepare(_ text: String, format: ArticleBodyFormat, fallbackTitle: String,
                                reportFallback: Bool = true) -> ArticleDraft {
        var draft = ArticleDraft()
        draft.contentFormat = format
        draft.title = fallbackTitle.isEmpty ? L("新文章", "New Article") : fallbackTitle
        let normalizedText = normalized(text)
        draft.body = normalizedText
        guard format == .markdown else {
            if reportFallback {
                draft.notices.append(L("已使用文件名作为标题，可在加入前修改。", "The file name was used as the title. You can change it before adding the article."))
            }
            return draft
        }
        var lines = normalizedText.components(separatedBy: "\n")
        while lines.first?.trimmingCharacters(in: .whitespaces).isEmpty == true { lines.removeFirst() }
        var rebuilt = false
        var preservesOriginalMarkdown = false
        if lines.first?.trimmingCharacters(in: .whitespaces) == "---" {
            if let yaml = frontMatter(lines) {
                if yaml.isSimple {
                    lines = Array(lines.dropFirst(yaml.lineCount))
                    while lines.first?.trimmingCharacters(in: .whitespaces).isEmpty == true { lines.removeFirst() }
                    draft.apply(yaml.values)
                    if let yamlTitle = yaml.values["title"], !yamlTitle.isEmpty { draft.title = yamlTitle }
                    draft.notices.append(L("已读取文件头中的文章信息，可在下方确认或修改。", "Article information was read from the file header. Review or edit it below."))
                    rebuilt = true
                } else {
                    // Unrecognized fields and nested YAML stay visible and exportable.
                    draft.notices.append(L("文件头含有暂不支持的字段或结构，已原样保留在正文中。", "The file header contains unsupported fields or structures and has been kept in the body."))
                    draft.body = lines.joined(separator: "\n")
                    draft.addUnsupportedNotices()
                    return draft
                }
            } else {
                draft.notices.append(L("未找到完整的文件头结束标记，已保留原文。", "The file header has no closing marker. The original text has been kept."))
            }
        }
        if let first = lines.first, let parsedHeading = heading(first),
           !rebuilt || draft.title == fallbackTitle || parsedHeading.title == draft.title {
            draft.title = parsedHeading.title
            lines.removeFirst()
            while lines.first?.trimmingCharacters(in: .whitespaces).isEmpty == true { lines.removeFirst() }
            var values: [String: String] = [:]
            while !lines.isEmpty {
                if lines[0].trimmingCharacters(in: .whitespaces).isEmpty { lines.removeFirst(); continue }
                guard let field = metadataField(lines[0]) else { break }
                if values[field.key] == nil, !field.value.isEmpty { values[field.key] = field.value }
                lines.removeFirst()
            }
            draft.apply(values, onlyEmpty: true)
            draft.body = lines.joined(separator: "\n")
            if !rebuilt, parsedHeading.level <= 2,
               let parsed = try? ArticleMarkdownDocument.parse(text), parsed.title == draft.title {
                preservesOriginalMarkdown = true
            } else if !rebuilt {
                draft.notices.append(L("已识别文章标题并转换为可编辑的阅读格式。", "The article title was recognized and converted to the editable reading format."))
            }
        } else if lines.count > 1, isSetextUnderline(lines[1]), !lines[0].trimmingCharacters(in: .whitespaces).isEmpty,
                  !rebuilt || draft.title == fallbackTitle {
            draft.title = lines[0].trimmingCharacters(in: .whitespaces)
            draft.body = lines.dropFirst(2).joined(separator: "\n").trimmingCharacters(in: .newlines)
            draft.notices.append(L("已识别文章标题并转换为可编辑的阅读格式。", "The article title was recognized and converted to the editable reading format."))
        } else {
            draft.body = lines.joined(separator: "\n")
            if !rebuilt, reportFallback {
                draft.notices.append(L("没有检测到文章标题，已使用文件名；正文已完整保留。", "No article title was detected. The file name was used and the full body was kept."))
            }
        }
        if let parsed = try? ArticleMarkdownDocument.parse(text), parsed.title == draft.title {
            if let value = parsed.metadata.author { draft.author = value }
            if let value = parsed.metadata.date { draft.date = value }
            if let value = parsed.metadata.source {
                draft.source = value
                draft.sourceURL = parsed.metadata.sourceURL?.absoluteString ?? draft.sourceURL
            }
            if preservesOriginalMarkdown {
                draft.originalMarkdown = text
                draft.originalFields = draft.fields
            }
        }
        draft.addUnsupportedNotices()
        return draft
    }

    private mutating func apply(_ values: [String: String], onlyEmpty: Bool = false) {
        if let value = values["author"], !onlyEmpty || author.isEmpty { author = value }
        if let value = values["date"], !onlyEmpty || date.isEmpty { date = value }
        if let value = values["source"], !onlyEmpty || source.isEmpty {
            let parsed = Self.sourceField(value)
            source = parsed.label
            if sourceURL.isEmpty { sourceURL = parsed.url }
        }
        if let value = values["url"], !onlyEmpty || sourceURL.isEmpty { sourceURL = value }
    }

    private mutating func addUnsupportedNotices() {
        guard resolvedContentFormat == .markdown else { return }
        let pattern = #"(?m)(!\[[^\]]*\]\(|^\s*\||\[\^[^\]]+\]|^\s*(```|~~~|\$\$)|^\s*<[A-Za-z!/])"#
        if body.range(of: pattern, options: .regularExpression) != nil {
            notices.append(L("图片、表格、脚注、代码或公式暂以可读文本显示；原始内容会保留。", "Images, tables, footnotes, code or formulas are shown as readable text for now. The original content is kept."))
        }
    }

    private static func detectBodyFormat(_ text: String) -> ArticleBodyFormat {
        func hasFormatting(_ node: any Markup) -> Bool {
            switch node {
            case is Heading, is BlockQuote, is ListItem, is Strong, is Emphasis,
                 is Link, is Markdown.Image, is InlineCode, is CodeBlock,
                 is ThematicBreak, is LineBreak:
                return true
            default:
                return node.children.contains(where: hasFormatting)
            }
        }
        return hasFormatting(Document(parsing: ArticleMarkdownDocument.normalizingChineseHeadings(in: normalized(text))))
            ? .markdown : .plainText
    }

    private static func normalized(_ value: String) -> String {
        let text = value.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        return text.hasPrefix("\u{FEFF}") ? String(text.dropFirst()) : text
    }

    private static func singleLine(_ value: String) -> String {
        value.split(whereSeparator: \.isNewline).joined(separator: " ").trimmingCharacters(in: .whitespaces)
    }

    private static func heading(_ line: String) -> (title: String, level: Int)? {
        let line = ArticleMarkdownDocument.normalizingChineseHeadings(in: line)
        guard let expression = try? NSRegularExpression(pattern: #"^ {0,3}(#{1,6})[ \t]+(.+?)[ \t]*$"#),
              let match = expression.firstMatch(in: line, range: NSRange(location: 0, length: (line as NSString).length)) else { return nil }
        let source = line as NSString
        let value = source.substring(with: match.range(at: 2))
            .replacingOccurrences(of: #"[ \t]+#+[ \t]*$"#, with: "", options: .regularExpression)
            .trimmingCharacters(in: .whitespaces)
        guard !value.isEmpty else { return nil }
        return (plainTitle(value), source.substring(with: match.range(at: 1)).count)
    }

    private static func plainTitle(_ value: String) -> String {
        value.replacingOccurrences(of: #"\[([^\]]+)\]\([^)]*\)"#, with: "$1", options: .regularExpression)
            .replacingOccurrences(of: #"(?<!\w)(\*{1,3}|_{1,3})(.+?)\1(?!\w)"#, with: "$2", options: .regularExpression)
            .replacingOccurrences(of: #"`+([^`]+)`+"#, with: "$1", options: .regularExpression)
            .replacingOccurrences(of: #"\\([\\`*{}\[\]()#+.!_>~-])"#, with: "$1", options: .regularExpression)
    }

    private static func metadataField(_ line: String) -> ArticleHeaderField? { ArticleHeaderField.parse(line) }

    private static func sourceField(_ value: String) -> (label: String, url: String) {
        guard let expression = try? NSRegularExpression(pattern: #"^\[([^\]]+)\]\((.+)\)$"#),
              let match = expression.firstMatch(in: value, range: NSRange(location: 0, length: (value as NSString).length)) else { return (value, "") }
        let text = value as NSString
        let label = text.substring(with: match.range(at: 1))
        let target = text.substring(with: match.range(at: 2))
        guard let url = URL(string: target), ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
              let host = url.host, !host.isEmpty else { return (label, "") }
        return (label, url.absoluteString)
    }

    private static func isSetextUnderline(_ line: String) -> Bool {
        line.range(of: #"^ {0,3}(=+|-+)[ \t]*$"#, options: .regularExpression) != nil
    }

    private struct FrontMatter {
        var values: [String: String]
        var lineCount: Int
        var isSimple: Bool
    }

    private static func frontMatter(_ lines: [String]) -> FrontMatter? {
        guard let closing = lines.indices.dropFirst().first(where: {
            ["---", "..."].contains(lines[$0].trimmingCharacters(in: .whitespaces))
        }) else { return nil }
        var values: [String: String] = [:]
        var isSimple = true
        for line in lines[1..<closing] {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.isEmpty || trimmed.hasPrefix("#") { continue }
            guard let colon = trimmed.firstIndex(of: ":") else { isSimple = false; continue }
            let sourceKey = String(trimmed[..<colon]).lowercased().trimmingCharacters(in: .whitespaces)
            let key: String
            switch sourceKey {
            case "title", "标题": key = "title"
            case "author", "authors", "作者": key = "author"
            case "date", "published", "日期", "发表日期", "写作日期": key = "date"
            case "source", "来源": key = "source"
            case "url", "source_url", "sourceurl", "原文链接": key = "url"
            default: isSimple = false; continue
            }
            var value = String(trimmed[trimmed.index(after: colon)...]).trimmingCharacters(in: .whitespaces)
            if value.hasPrefix("\"") {
                guard let decoded = try? JSONDecoder().decode(String.self, from: Data(value.utf8)) else { isSimple = false; continue }
                value = decoded
            } else if value.hasPrefix("'") {
                guard value.count >= 2, value.hasSuffix("'") else { isSimple = false; continue }
                value = String(value.dropFirst().dropLast()).replacingOccurrences(of: "''", with: "'")
            } else {
                if let comment = value.range(of: " #") { value = String(value[..<comment.lowerBound]).trimmingCharacters(in: .whitespaces) }
                if value.first.map({ "[{|>&*!".contains($0) }) == true || value.contains(": ") {
                    isSimple = false
                    continue
                }
            }
            if values[key] == nil, !value.isEmpty { values[key] = singleLine(value) }
        }
        return FrontMatter(values: values, lineCount: closing + 1, isSimple: isSimple)
    }

    private static func escapeInline(_ value: String) -> String {
        var output = ""
        for character in value {
            if character == "&" { output += "&amp;" }
            else {
            if "\\`*_{}[]()#+-.!:<>|~".contains(character) { output.append("\\") }
                output.append(character)
            }
        }
        return output
    }

    private static func plainTextMarkdown(_ value: String) -> String {
        let lines = value.components(separatedBy: "\n")
        return lines.enumerated().map { index, line in
            let leading = line.prefix(while: { $0 == " " || $0 == "\t" })
            let remainder = line.dropFirst(leading.count)
            var escaped = leading.map { $0 == "\t" ? "&#9;" : "&#32;" }.joined() + escapeInline(String(remainder))
            if !line.isEmpty, index + 1 < lines.count, !lines[index + 1].isEmpty { escaped += "\\" }
            return escaped
        }.joined(separator: "\n")
    }

    /// The document reader recognizes metadata immediately below the title.
    /// Metadata-looking prose entered in the body must remain selectable prose.
    private static func protectBodyMetadata(_ value: String) -> String {
        var lines = value.components(separatedBy: "\n")
        for index in lines.indices {
            if lines[index].trimmingCharacters(in: .whitespaces).isEmpty { continue }
            guard metadataField(lines[index]) != nil,
                  let colon = lines[index].firstIndex(where: { $0 == ":" || $0 == "：" }) else { break }
            // CommonMark only escapes ASCII punctuation; encode a full-width
            // colon so the text stays identical while bypassing header parsing.
            if lines[index][colon] == ":" { lines[index].insert("\\", at: colon) }
            else { lines[index].replaceSubrange(colon...colon, with: "&#65306;") }
        }
        return lines.joined(separator: "\n")
    }
}

enum ArticleTemplate {
    static var markdown: String { markdown(for: AppLanguageStore.shared.language) }

    static func markdown(for language: InterfaceLanguage) -> String {
        switch language {
        case .english:
            return """
            # Title

            Author: Name (optional)
            Date: 2026-01-01  (optional)
            Source: [Original publisher](https://example.com)  (optional)

            Body text

            ## Heading

            Body text

            """
        case .chinese:
            return """
            # 文章标题

            作者：姓名（选填）
            日期：2026-01-01（选填）
            来源：原始出版来源（选填）

            正文内容

            ##正文小标题

            正文内容

            """
        }
    }
}
